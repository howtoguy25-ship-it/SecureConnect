// Flag emoji is derived from the ISO 3166-1 alpha-2 code at render time (two Unicode
// "regional indicator symbol" characters) rather than typed out by hand for all ~195
// countries below -- that would be near-guaranteed to have a typo/mismatch somewhere.
export function countryFlagEmoji(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(0x1f1e6 + char.charCodeAt(0) - 65));
}

